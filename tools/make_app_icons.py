#!/usr/bin/env python3
"""Draws the app icon: a white seedling on AgriDose green (same as the dashboard).

Writes
  app/src/main/res/mipmap-*dpi/ic_launcher.png          for Android 7 (5 sizes)
  app/src/main/res/drawable/ic_launcher_foreground.xml  vector seedling for Android 8+
Plain Python, no extra packages.  Run:  python tools/make_app_icons.py
"""
import math
import pathlib
import struct
import zlib

RES = pathlib.Path(__file__).resolve().parent.parent / "app" / "src" / "main" / "res"
GREEN = (0x14, 0x53, 0x2D)
WHITE = (0xFF, 0xFF, 0xFF)

# The seedling, in units of the icon's width (0 to 1, y going down).
STEM = (0.47, 0.40, 0.53, 0.74)                      # x0, y0, x1, y1
LEAVES = [(0.37, 0.345, 0.15, 0.075, 30),            # cx, cy, half-length, half-width, angle
          (0.64, 0.32, 0.17, 0.085, -35)]
GROUND = (0.30, 0.70, 0.75, 0.03)                    # x0, x1, y centre, radius


def is_white(x, y):
    sx0, sy0, sx1, sy1 = STEM
    if sx0 <= x <= sx1 and sy0 <= y <= sy1:
        return True
    for cx, cy, a, b, ang in LEAVES:
        t = math.radians(ang)
        u = (x - cx) * math.cos(t) + (y - cy) * math.sin(t)
        v = -(x - cx) * math.sin(t) + (y - cy) * math.cos(t)
        if (u / a) ** 2 + (v / b) ** 2 <= 1:
            return True
    gx0, gx1, gy, r = GROUND
    end = min(max(x, gx0), gx1)
    return (x - end) ** 2 + (y - gy) ** 2 <= r * r


def write_png(path, size, samples=3):
    rows = []
    for py in range(size):
        row = bytearray([0])                         # PNG filter type 0
        for px in range(size):
            hits = sum(is_white((px + (i + 0.5) / samples) / size, (py + (j + 0.5) / samples) / size)
                       for i in range(samples) for j in range(samples))
            k = hits / samples ** 2
            row += bytes(round(g + (w - g) * k) for g, w in zip(GREEN, WHITE))
        rows.append(bytes(row))

    def chunk(tag, data):
        return struct.pack(">I", len(data)) + tag + data + struct.pack(">I", zlib.crc32(tag + data) & 0xFFFFFFFF)

    png = (b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", size, size, 8, 2, 0, 0, 0))
           + chunk(b"IDAT", zlib.compress(b"".join(rows), 9)) + chunk(b"IEND", b""))
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(png)


def vector_foreground():
    """Same shapes as a vector drawable. Adaptive icons are 108 x 108 and only
    the middle 72 is sure to show, so the 0..1 icon is placed in 18..90."""
    def p(x, y):
        return f"{18 + 72 * x:.2f},{18 + 72 * y:.2f}"

    def s(v):
        return f"{72 * v:.2f}"

    paths = []
    sx0, sy0, sx1, sy1 = STEM
    paths.append(f"M{p(sx0, sy0)} L{p(sx1, sy0)} L{p(sx1, sy1)} L{p(sx0, sy1)} Z")
    for cx, cy, a, b, ang in LEAVES:                 # an ellipse = two half arcs
        t = math.radians(ang)
        x1, y1 = cx + a * math.cos(t), cy + a * math.sin(t)
        x2, y2 = cx - a * math.cos(t), cy - a * math.sin(t)
        paths.append(f"M{p(x1, y1)} A{s(a)},{s(b)} {ang} 1,1 {p(x2, y2)} A{s(a)},{s(b)} {ang} 1,1 {p(x1, y1)} Z")
    gx0, gx1, gy, r = GROUND
    paths.append(f"M{p(gx0, gy - r)} L{p(gx1, gy - r)} A{s(r)},{s(r)} 0 0,1 {p(gx1, gy + r)} "
                 f"L{p(gx0, gy + r)} A{s(r)},{s(r)} 0 0,1 {p(gx0, gy - r)} Z")
    body = "\n".join(f'    <path android:fillColor="#FFFFFFFF" android:pathData="{d}" />' for d in paths)
    return ('<?xml version="1.0" encoding="utf-8"?>\n'
            "<!-- GENERATED by tools/make_app_icons.py -->\n"
            '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
            '    android:width="108dp" android:height="108dp"\n'
            '    android:viewportWidth="108" android:viewportHeight="108">\n'
            f"{body}\n</vector>\n")


if __name__ == "__main__":
    for folder, size in [("mdpi", 48), ("hdpi", 72), ("xhdpi", 96), ("xxhdpi", 144), ("xxxhdpi", 192)]:
        write_png(RES / f"mipmap-{folder}" / "ic_launcher.png", size)
        print(f"mipmap-{folder}/ic_launcher.png  {size}px")
    out = RES / "drawable" / "ic_launcher_foreground.xml"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(vector_foreground(), encoding="utf-8", newline="\n")
    print("drawable/ic_launcher_foreground.xml")
