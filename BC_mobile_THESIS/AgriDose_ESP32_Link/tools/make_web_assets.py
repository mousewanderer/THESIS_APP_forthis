#!/usr/bin/env python3
"""Turns the dashboard files in www/ into web_assets.h.

The page lives inside the firmware (in flash), not on the SD card, so the
dashboard still works with no card or a broken card. Text files are
gzipped first; the phone's browser unpacks them (Content-Encoding: gzip).

Run this after every change in www/, then upload the sketch again:
    python AgriDose_ESP32_Link/tools/make_web_assets.py
"""
import gzip
import pathlib

SKETCH = pathlib.Path(__file__).resolve().parent.parent
WWW = SKETCH / "www"
OUT = SKETCH / "web_assets.h"

# file in www/, the web addresses that serve it, content type, gzip it?
FILES = [
    ("index.html",           ["/", "/index.html"],          "text/html; charset=utf-8",               True),
    ("agri.js",              ["/agri.js"],                  "application/javascript; charset=utf-8",  True),
    ("app.js",               ["/app.js"],                   "application/javascript; charset=utf-8",  True),
    ("app.css",              ["/app.css"],                  "text/css; charset=utf-8",                True),
    ("manifest.webmanifest", ["/manifest.webmanifest"],     "application/manifest+json",              True),
    ("icon-192.png",         ["/icon-192.png", "/favicon.ico"], "image/png",                          False),
    ("icon-512.png",         ["/icon-512.png"],             "image/png",                              False),
]


def c_array(name, data):
    lines = []
    for i in range(0, len(data), 16):
        lines.append("  " + ", ".join(f"0x{b:02x}" for b in data[i:i + 16]) + ",")
    return f"static const uint8_t {name}[] = {{\n" + "\n".join(lines) + "\n};\n"


def main():
    parts = [
        "// GENERATED by tools/make_web_assets.py from the files in www/.\n"
        "// Do not edit by hand: change www/ and run the script again.\n"
        "// Include this file in web_server.cpp only (one copy in flash).\n"
        "#pragma once\n#include <Arduino.h>\n\n"
        "struct WebAsset {\n"
        "  const char* path;       // web address, e.g. \"/app.js\"\n"
        "  const char* type;       // content type\n"
        "  bool gzipped;           // true = send with Content-Encoding: gzip\n"
        "  const uint8_t* data;\n"
        "  size_t len;\n"
        "};\n\n"
    ]
    table = []
    total = 0
    for i, (file, paths, ctype, gz) in enumerate(FILES):
        raw = (WWW / file).read_bytes()
        data = gzip.compress(raw, compresslevel=9, mtime=0) if gz else raw
        name = f"ASSET_{i}"
        parts.append(f"// {file}: {len(raw)} bytes" + (f", {len(data)} gzipped" if gz else "") + "\n")
        parts.append(c_array(name, data) + "\n")
        for p in paths:
            table.append(f'  {{"{p}", "{ctype}", {"true" if gz else "false"}, {name}, sizeof({name})}},')
        total += len(data)
        print(f"{file:22} {len(raw):6} bytes -> {len(data):6}")
    parts.append("static const WebAsset WEB_ASSETS[] = {\n" + "\n".join(table) + "\n};\n")
    parts.append("static const size_t WEB_ASSET_COUNT = sizeof(WEB_ASSETS) / sizeof(WEB_ASSETS[0]);\n")
    OUT.write_text("".join(parts), encoding="ascii", newline="\n")
    print(f"total {total} bytes in flash -> {OUT.name}")


if __name__ == "__main__":
    main()
